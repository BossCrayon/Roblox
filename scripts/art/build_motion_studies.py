"""Blender motion studies and matching procedural Luau accents; no external assets."""
import json, pathlib, math
ROOT=pathlib.Path(__file__).resolve().parents[2]
# Seven joint rotation accents in degrees. Deliberate anticipation / strike / recoil / settle.
roles=['Root','Waist','Neck','LeftShoulder','RightShoulder','LeftHip','RightHip']
profiles={
'Seer':[[8,-12,-4],[5,-8,-3],[-6,8,2],[-18,-14,-20],[-25,18,24],[-8,0,-4],[8,0,4]],
'Marauder':[[10,20,6],[7,16,4],[-5,-12,-3],[12,-16,-12],[-28,24,18],[-12,0,4],[12,0,-4]],
'Apprentice':[[6,0,0],[5,0,0],[-8,0,0],[-24,-20,-22],[-24,20,22],[-8,0,-3],[8,0,3]],
'MeleeRight':[[8,-22,-6],[6,-18,-4],[-4,12,2],[14,0,-12],[-28,-18,18],[-12,0,-5],[12,0,5]],
'MeleeLeft':[[8,22,6],[6,18,4],[-4,-12,-2],[-28,18,-18],[14,0,12],[12,0,-5],[-12,0,5]],
}
beats=[(0,-.45),(.16,1),(.30,.8),(.56,-.32),(.78,.12),(1,0)]
data={name:[{'Time':t,'Pose':{role:[round(v*gain,4) for v in xyz] for role,xyz in zip(roles,pose)}} for t,gain in beats] for name,pose in profiles.items()}
(ROOT/'art/motion/tracks.json').write_text(json.dumps(data,indent=2)+'\n')
def lua(x):
 if isinstance(x,dict): return '{'+','.join('['+json.dumps(k)+']='+lua(v) for k,v in x.items())+'}'
 if isinstance(x,list): return '{'+','.join(map(lua,x))+'}'
 return str(x)
(ROOT/'src/ReplicatedStorage/Shared/MotionTracks.lua').write_text('--!strict\n-- Original animation staging, not a claim about canonical combat gestures.\n-- Generated by scripts/art/build_motion_studies.py; shared with the Blender studies.\nreturn '+lua(data)+'\n')
try: import bpy
except ImportError: raise SystemExit('Luau/JSON generated; run with Blender to build the editable studies.')
bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
for index,(name,track) in enumerate(data.items()):
 bpy.ops.object.armature_add(location=(index*5,0,0));rig=bpy.context.object;rig.name=name+' Motion Study'
 bpy.ops.object.mode_set(mode='EDIT');rig.data.edit_bones.remove(rig.data.edit_bones[0])
 locations=[((0,0,1),(0,0,1.5)),((0,0,1.5),(0,0,2.2)),((0,0,2.2),(0,0,2.6)),((-.35,0,2.1),(-1,0,1.5)),((.35,0,2.1),(1,0,1.5)),((-.2,0,1.1),(-.2,0,.1)),((.2,0,1.1),(.2,0,.1))]
 for role,(head,tail) in zip(roles,locations):
  bone=rig.data.edit_bones.new(role);bone.head=head;bone.tail=tail
  if role!='Root': bone.parent=rig.data.edit_bones['Root' if role in ('Waist','LeftHip','RightHip') else 'Waist']
 bpy.ops.object.mode_set(mode='POSE')
 for key in track:
  for role,angles in key['Pose'].items():
   bone=rig.pose.bones[role];bone.rotation_mode='XYZ'
   # Roblox Y-up -> Blender Z-up reference rotation; this is a study rig, not an R15 import rig.
   bone.rotation_euler=tuple(math.radians(a) for a in (angles[0],-angles[2],angles[1]));bone.keyframe_insert('rotation_euler',frame=1+round(key['Time']*60))
 bpy.ops.object.mode_set(mode='OBJECT');rig.show_in_front=True
 rig.animation_data.action.name=name+' Anticipation Strike Recoil'
bpy.context.scene.frame_end=61;bpy.context.scene.render.fps=60
bpy.ops.wm.save_as_mainfile(filepath=str(ROOT/'art/motion/MysteriesMotionStudies.blend'))
